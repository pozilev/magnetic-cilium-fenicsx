def locate_bottom_and_top_facets(domain, params: ModelParams):
    fdim = domain.topology.dim - 1
    bottom_facets = mesh.locate_entities_boundary(
        domain, fdim, lambda x: np.isclose(x[2], -params.substrate_thickness, atol=1e-12)
    )
    control_facets = mesh.locate_entities_boundary(
        domain, fdim, lambda x: np.isclose(x[2], params.L, atol=1e-12)
    )
    if len(bottom_facets) == 0:
        raise RuntimeError("No bottom substrate facets found.")
    if len(control_facets) == 0:
        raise RuntimeError("No top control facets found.")
    return bottom_facets, control_facets


def solve_hyperelasticity_displacement_control_3d(domain, E, nu, params: ModelParams, step_callback=None):
    log.info("model: nonlinear Neo-Hookean top-face displacement-control mechanics")
    gdim = domain.geometry.dim
    fdim = domain.topology.dim - 1
    bottom_facets, control_facets = locate_bottom_and_top_facets(domain, params)

    log.info("BC: bottom substrate facets = %d", len(bottom_facets))
    log.info("BC: top control facets = %d", len(control_facets))

    V = fem.functionspace(domain, ("Lagrange", params.element_degree, (gdim,)))
    log.info("space: vector P%d global dofs = %d", params.element_degree, V.dofmap.index_map.size_global * V.dofmap.index_map_bs)

    zero = default_scalar_type(0.0)
    bcs = []
    for i in range(3):
        bottom_dofs_i = fem.locate_dofs_topological(V.sub(i), fdim, bottom_facets)
        bcs.append(fem.dirichletbc(zero, bottom_dofs_i, V.sub(i)))

    control_ux = fem.Constant(domain, default_scalar_type(0.0))
    control_dofs_x = fem.locate_dofs_topological(V.sub(0), fdim, control_facets)
    if len(control_dofs_x) == 0:
        raise RuntimeError("No x-dofs found on top control facets.")
    bcs.append(fem.dirichletbc(control_ux, control_dofs_x, V.sub(0)))

    u = fem.Function(V); u.name = "displacement"
    du = ufl.TrialFunction(V)
    v = ufl.TestFunction(V)

    Pi = neo_hookean_energy(u, E, nu) * ufl.dx
    residual = ufl.derivative(Pi, u, v)
    jacobian = ufl.derivative(residual, u, du)

    problem = fem_petsc.NewtonSolverNonlinearProblem(residual, u, bcs=bcs, J=jacobian)
    solver = nls_petsc.NewtonSolver(domain.comm, problem)
    solver.atol = 1e-7
    solver.rtol = 1e-6
    solver.max_it = 25
    solver.convergence_criterion = "incremental"

    ksp = solver.krylov_solver
    ksp.setType(PETSc.KSP.Type.CG)
    pc = ksp.getPC(); pc.setType(PETSc.PC.Type.GAMG)
    ksp.setTolerances(rtol=1e-6, atol=1e-10, max_it=1000)

    log.info("BC: final top displacement delta_x = %.6e m", params.delta_x)
    log.info("solve: displacement continuation steps = %d", params.n_steps)

    for step in range(1, params.n_steps + 1):
        alpha = step / params.n_steps
        control_ux.value = default_scalar_type(alpha * params.delta_x)
        n_iter, converged = solver.solve(u)
        u.x.scatter_forward()
        log.info(
            "nonlinear step %02d/%02d: delta_x = %.6e m, Newton iters = %d, converged = %s",
            step, params.n_steps, alpha * params.delta_x, n_iter, converged,
        )
        if step_callback is not None:
            step_callback(
                step=step,
                total_steps=params.n_steps,
                alpha=alpha,
                displacement=u,
                domain=domain,
                params=params,
                newton_iterations=n_iter,
                converged=bool(converged),
            )
        if not converged:
            raise RuntimeError(f"Newton did not converge at step {step}/{params.n_steps}")

    local_max_ux = np.max(np.real(u.x.array[control_dofs_x]))
    max_ux = domain.comm.allreduce(local_max_ux, op=MPI.MAX)
    reaction_force_x = compute_reaction_force_x(domain, u, E, nu, control_facets)

    log.info("postprocess: max top u_x = %.9e m", max_ux)
    log.info("postprocess: reaction force x = %.9e N", reaction_force_x)
    log.info("postprocess: reaction force x = %.9e uN", reaction_force_x * 1e6)
    return u, max_ux, reaction_force_x, bottom_facets, control_facets


def compute_reaction_force_x(domain, u, E, nu, control_facets):
    fdim = domain.topology.dim - 1
    values = np.ones(len(control_facets), dtype=np.int32)
    order = np.argsort(control_facets)
    control_tags = mesh.meshtags(domain, fdim, control_facets[order], values[order])
    ds = ufl.Measure("ds", domain=domain, subdomain_data=control_tags)
    N = ufl.FacetNormal(domain)
    P = first_piola_stress(u, E, nu)
    e_x = ufl.as_vector((1.0, 0.0, 0.0))
    reaction_form = fem.form(ufl.dot(P * N, e_x) * ds(1))
    local_reaction = fem.assemble_scalar(reaction_form)
    reaction = domain.comm.allreduce(local_reaction, op=MPI.SUM)
    return abs(reaction)


