def make_material_field(domain, params: ModelParams):
    log.info("tagging: assigning material ids and coefficients")
    tdim = domain.topology.dim
    Q = fem.functionspace(domain, ("DG", 0))

    material = fem.Function(Q); material.name = "material_id"
    E = fem.Function(Q); E.name = "young_modulus"
    nu = fem.Function(Q); nu.name = "poisson_ratio"

    num_cells = domain.topology.index_map(tdim).size_local
    cell_ids = np.arange(num_cells, dtype=np.int32)
    mids = mesh.compute_midpoints(domain, tdim, cell_ids)

    substrate_count = lower_count = upper_count = 0
    for c, z in zip(cell_ids, mids[:, 2]):
        dof = Q.dofmap.cell_dofs(int(c))[0]
        if z < 0.0:
            material.x.array[dof] = 0.0
            E.x.array[dof] = params.E_pdms
            nu.x.array[dof] = params.nu_pdms
            substrate_count += 1
        elif z < params.L1:
            material.x.array[dof] = 1.0
            E.x.array[dof] = params.E_pdms
            nu.x.array[dof] = params.nu_pdms
            lower_count += 1
        else:
            material.x.array[dof] = 2.0
            E.x.array[dof] = params.E_magnetic
            nu.x.array[dof] = params.nu_magnetic
            upper_count += 1

    material.x.scatter_forward(); E.x.scatter_forward(); nu.x.scatter_forward()
    log.info("tagging: substrate PDMS cells = %d", substrate_count)
    log.info("tagging: lower cilium PDMS cells = %d", lower_count)
    log.info("tagging: upper magnetic-composite cells = %d", upper_count)
    return material, E, nu


def make_material_field_from_cell_ids(domain, material_cell_ids: np.ndarray):
    Q = fem.functionspace(domain, ("DG", 0))
    material = fem.Function(Q)
    material.name = "material_id"
    num_cells = domain.topology.index_map(domain.topology.dim).size_local
    if len(material_cell_ids) != num_cells:
        raise RuntimeError(f"Material array length mismatch: got {len(material_cell_ids)}, expected {num_cells}.")
    for c in range(num_cells):
        dof = Q.dofmap.cell_dofs(int(c))[0]
        material.x.array[dof] = float(material_cell_ids[c])
    material.x.scatter_forward()
    return material


def extract_material_cell_ids(material) -> np.ndarray:
    Q = material.function_space
    num_cells = Q.mesh.topology.index_map(Q.mesh.topology.dim).size_local
    arr = np.zeros(num_cells, dtype=np.int32)
    for c in range(num_cells):
        dof = Q.dofmap.cell_dofs(int(c))[0]
        arr[c] = int(round(float(material.x.array[dof])))
    return arr


def lame_parameters(E, nu):
    mu = E / (2.0 * (1.0 + nu))
    lmbda = E * nu / ((1.0 + nu) * (1.0 - 2.0 * nu))
    return mu, lmbda


# -----------------------------------------------------------------------------
# Hyperelasticity
# -----------------------------------------------------------------------------


def neo_hookean_energy(u, E, nu):
    mu, lmbda = lame_parameters(E, nu)
    I = ufl.Identity(3)
    Fdef = I + ufl.grad(u)
    C = Fdef.T * Fdef
    Ic = ufl.tr(C)
    J = ufl.det(Fdef)
    return (mu / 2.0) * (Ic - 3.0) - mu * ufl.ln(J) + (lmbda / 2.0) * (ufl.ln(J)) ** 2


def first_piola_stress(u, E, nu):
    mu, lmbda = lame_parameters(E, nu)
    I = ufl.Identity(3)
    Fdef = I + ufl.grad(u)
    J = ufl.det(Fdef)
    FinvT = ufl.inv(Fdef).T
    return mu * (Fdef - FinvT) + lmbda * ufl.ln(J) * FinvT


def cauchy_stress(u, E, nu):
    I = ufl.Identity(3)
    Fdef = I + ufl.grad(u)
    J = ufl.det(Fdef)
    P = first_piola_stress(u, E, nu)
    return (1.0 / J) * P * Fdef.T


