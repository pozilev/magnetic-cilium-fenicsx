def get_interpolation_points(function_space):
    points = function_space.element.interpolation_points
    return points() if callable(points) else points


def interpolate_scalar_DG0(domain, expr, name: str):
    Q = fem.functionspace(domain, ("DG", 0))
    q = fem.Function(Q); q.name = name
    expression = fem.Expression(expr, get_interpolation_points(Q))
    cells = np.arange(domain.topology.index_map(domain.topology.dim).size_local, dtype=np.int32)
    try:
        q.interpolate(expression, cells)
    except TypeError:
        q.interpolate(expression)
    q.x.scatter_forward()
    return q


def minmax_function(domain, f):
    arr = np.real(f.x.array)
    local_min = float(np.min(arr)) if arr.size else np.inf
    local_max = float(np.max(arr)) if arr.size else -np.inf
    return domain.comm.allreduce(local_min, op=MPI.MIN), domain.comm.allreduce(local_max, op=MPI.MAX)


def compute_J_field(domain, u):
    I = ufl.Identity(3)
    Fdef = I + ufl.grad(u)
    J = interpolate_scalar_DG0(domain, ufl.det(Fdef), "J_detF")
    J_min, J_max = minmax_function(domain, J)
    return J, J_min, J_max


def compute_von_mises_field(domain, u, E, nu):
    sigma = cauchy_stress(u, E, nu)
    I = ufl.Identity(3)
    s = sigma - (1.0 / 3.0) * ufl.tr(sigma) * I
    vm = interpolate_scalar_DG0(domain, ufl.sqrt((3.0 / 2.0) * ufl.inner(s, s)), "von_mises_DG0")
    vm_min, vm_max = minmax_function(domain, vm)
    return vm, vm_min, vm_max


def compute_material_volumes(domain, material) -> Dict[int, float]:
    dx = ufl.Measure("dx", domain=domain)
    volumes = {}
    for mat_id in (0, 1, 2):
        indicator = ufl.conditional(ufl.lt((material - float(mat_id)) * (material - float(mat_id)), 0.25), 1.0, 0.0)
        local_vol = fem.assemble_scalar(fem.form(indicator * dx))
        volumes[mat_id] = domain.comm.allreduce(local_vol, op=MPI.SUM)
    return volumes


def evaluate_displacement_at_geometry_vertices(domain, u):
    gdim = domain.geometry.dim
    V1 = fem.functionspace(domain, ("Lagrange", 1, (gdim,)))
    u1 = fem.Function(V1)
    u1.name = "displacement_P1_for_magnetics"
    u1.interpolate(u)
    u1.x.scatter_forward()
    bs = V1.dofmap.index_map_bs
    u_values = np.real(u1.x.array).reshape((-1, bs))[:, :3]
    num_vertices = domain.topology.index_map(0).size_local
    if u_values.shape[0] != num_vertices:
        raise RuntimeError("P1 displacement dof count does not match geometry vertex count.")
    return u_values


def log_mesh_resolution_warning(params: ModelParams) -> None:
    elements_across_diameter = params.D / params.h_cilium
    log.info("mesh quality: elements across cilium diameter D/h_cilium = %.2f", elements_across_diameter)
    if elements_across_diameter < 4.0:
        log.warning("Cilium mesh is very coarse across diameter: D/h_cilium = %.2f. Reaction force may be unreliable.", elements_across_diameter)


def validate_result_quality(params: ModelParams, result: Dict) -> None:
    if "J_min" in result and result["J_min"] <= 0.0:
        raise RuntimeError(f"Invalid deformation: det(F) <= 0, min J = {result['J_min']}")
    if "reaction_force_x_uN" in result:
        rel_error = abs(result["reaction_force_x_uN"] - TARGET_REACTION_U_N) / TARGET_REACTION_U_N
        if result.get("study", "").startswith("final") and rel_error > 0.15:
            log.warning("Final run is far from target reaction: reaction = %.3f uN, target = %.3f uN, error = %.1f%%",
                        result["reaction_force_x_uN"], TARGET_REACTION_U_N, 100.0 * rel_error)


def save_results(domain, uh, material, E, nu, J_field, von_mises, params: ModelParams):
    import os
    log.info("output: writing VTK/PVD results")
    os.makedirs(params.outdir, exist_ok=True)
    vtk_path = os.path.join(params.outdir, "magnetic_cilium_3d.pvd")
    uh.name = "displacement"; material.name = "material_id"; E.name = "young_modulus"; nu.name = "poisson_ratio"
    J_field.name = "J_detF"; von_mises.name = "von_mises_DG0"
    with io.VTKFile(domain.comm, vtk_path, "w") as vtk:
        vtk.write_mesh(domain)
        vtk.write_function([uh, material, E, nu, J_field, von_mises])
    log.info("output: saved %s", vtk_path)
    return vtk_path
